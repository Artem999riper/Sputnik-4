const HELP_VIEW = { map: 'map', workers: 'workers', machinery: 'machinery', equipment: 'equipment', materials: 'materials', mto: 'mto', gruz: 'gruz', gtasks: 'gtasks', smg: 'smg', brigades: 'brigades', conv: 'conv', dash: 'start' };

function helpOpen(id) {
  if (!id) { const v = document.querySelector('.nt.on')?.dataset.v || 'map'; id = HELP_VIEW[v] || 'start'; }
  let ov = document.getElementById('help-ov');
  if (!ov) {
    ov = document.createElement('div'); ov.id = 'help-ov';
    ov.innerHTML = `<div id="help-box">
      <div id="help-nav"><input id="help-q" type="search" placeholder="🔍 Поиск по справке…" oninput="_helpNav()"><div id="help-list"></div>
        <div style="padding:8px 10px;border-top:1px solid var(--bd)"><button class="btn bs bsm" style="width:100%" onclick="helpClose();tourStart(true)">🎓 Пройти обучение (обзор)</button></div></div>
      <div id="help-main"><button id="help-x" onclick="helpClose()" title="Закрыть (Esc)">✕</button><div id="help-content"></div></div></div>`;
    ov.addEventListener('mousedown', e => { if (e.target === ov) helpClose(); });
    document.body.appendChild(ov);
    document.addEventListener('keydown', e => { if (e.key === 'Escape' && document.getElementById('help-ov')?.classList.contains('show') && !document.getElementById('tour-box')) { e.stopImmediatePropagation(); helpClose(); } }, true);
  }
  ov.classList.add('show');
  window._helpCur = id; _helpNav(); _helpShow(id);
}
function helpClose() { document.getElementById('help-ov')?.classList.remove('show'); }
function _helpNav() {
  const q = (document.getElementById('help-q')?.value || '').toLowerCase().trim();
  const strip = h => h.replace(/<[^>]+>/g, ' ').toLowerCase();
  const list = HELP.filter(s => !q || (s.title + ' ' + strip(s.html)).toLowerCase().includes(q));
  document.getElementById('help-list').innerHTML = list.map(s => `<div class="help-item${s.id === window._helpCur ? ' on' : ''}" onclick="_helpShow('${s.id}')">${s.icon} ${esc(s.title)}</div>`).join('') || '<div style="padding:10px;color:var(--tx3);font-size:12px">Ничего не найдено</div>';
}
function _helpShow(id) {
  const s = HELP.find(x => x.id === id) || HELP[0];
  window._helpCur = s.id;
  document.querySelectorAll('#help-list .help-item').forEach(el => el.classList.toggle('on', el.getAttribute('onclick') === `_helpShow('${s.id}')`));
  const q = (document.getElementById('help-q')?.value || '').trim();
  let html = s.html;
  if (q.length > 1) { const re = new RegExp('(' + q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')(?![^<]*>)', 'gi'); html = html.replace(re, '<mark>$1</mark>'); }
  document.getElementById('help-content').innerHTML = `<h2>${s.icon} ${esc(s.title)}</h2>
    ${s.demo ? `<button class="btn bp bsm" style="margin:2px 0 12px" onclick="helpDemo('${s.id}')">▶ Показать на экране</button>` : ''}
    ${s.view && s.view !== 'map' && !s.demo ? `<button class="btn bs bsm" style="margin:2px 0 12px" onclick="helpClose();switchView('${s.view}')">Открыть вкладку →</button>` : ''}
    <div class="help-text">${html}</div>`;
  document.getElementById('help-main').scrollTop = 0;
}
function helpDemo(id) {
  const s = HELP.find(x => x.id === id); if (!s || !s.demo) return;
  helpClose();
  if (s.demo === 'tour') { tourStart(true); return; }
  if (typeof closeModal === 'function' && !s.demo.some(st => st.act)) closeModal();
  tourRun(s.demo, () => helpOpen(id));
}
